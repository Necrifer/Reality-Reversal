const tesselatingType = 'kubejs:dimdoors_tesselating'

JEIAddedEvents.registerCategories(event => {
  const guiHelper = event.JEI_HELPERS.guiHelper
  event.custom(tesselatingType, category => {
    category.title('Tesselating Loom')
      .background(guiHelper.createBlankDrawable(136, 76))
      // KubeJS Additions stores category dimensions separately from its
      // background drawable. Without these explicit values, JEI retains the
      // default 16x16 icon dimensions and stacks 76px layouts only 16px apart.
      .setWidth(136)
      .setHeight(76)
      .icon(guiHelper.createDrawableItemStack(Item.of('dimdoors:tesselating_loom')))
      // KubeJS Additions requires this callback to return a Java boolean.
      // Coercing the validation result prevents the output object itself from
      // being returned and rejected with "Cannot convert {...} to boolean".
      .isRecipeHandled(recipe => !!(recipe && recipe.data && recipe.data.output))
      .handleLookup((builder, recipe, focuses) => {
        recipe.data.inputs.forEach((ingredient, index) => {
          if (!ingredient) return
          const x = 4 + (index % 3) * 18
          const y = 4 + Math.floor(index / 3) * 18
          const slot = builder.addSlot('INPUT', x, y)
          if (ingredient.item) slot.addItemStack(Item.of(ingredient.item, ingredient.count || 1))
          else if (ingredient.tag) slot.addItemStacks(Ingredient.of('#' + ingredient.tag).stacks)
        })
        builder.addSlot('OUTPUT', 106, 22).addItemStack(Item.of(recipe.data.output.item, recipe.data.output.count || 1))
      })
  })
})

JEIAddedEvents.registerRecipes(event => {
  tesselatingRecipes.forEach(recipe => event.custom(tesselatingType).add(recipe))
})

JEIAddedEvents.registerRecipeCatalysts(event => {
  event.data.addRecipeCatalyst(Item.of('dimdoors:tesselating_loom'), event.getCustomRecipeType(tesselatingType))
})
